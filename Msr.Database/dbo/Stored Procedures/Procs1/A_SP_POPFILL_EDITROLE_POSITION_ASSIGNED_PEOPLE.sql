








CREATE        PROCEDURE dbo.A_SP_POPFILL_EDITROLE_POSITION_ASSIGNED_PEOPLE
	@ID nvarchar(50),
	@strNTLogin nvarchar(50)
AS

SELECT p.FULL_NAME as SHOW, p.ID AS VALUE FROM A_ROLE_ASSIGNEE ra,A_APPROVED_PEOPLE p 
WHERE ra.ROLE = @ID  AND ra.PERSON = p.ID AND ra.STATUS = 'ACTIVE' AND [TYPE] = 'POSITION'










