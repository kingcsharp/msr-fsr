




CREATE    PROCEDURE dbo.A_SP_ZZ_EMAIL_GET_LIST_TO_SEND
@strNTLogin varchar(50)
AS
CREATE TABLE #TempItems	 (
	[ID] varchar(50)
)

INSERT INTO #TempItems SELECT ID
	FROM A_Z_EMAILS_TO_SEND
	WHERE STATUS = 'READY_TO_SEND'
UPDATE A_Z_EMAILS_TO_SEND SET STATUS = 'SEND_ATTEMPTED' WHERE ID IN (SELECT ID FROM #TempItems)
SELECT * FROM #TempItems












