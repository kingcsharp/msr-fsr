INNER JOIN DBO.PORTAL_PURCHASEORDERS AS PO ON (WO.REFERENCEPO = PO.REFERENCEPO) OR ((WO.REFERENCEPO IS NULL) AND (PO.REFERENCEPO IS NULL))
WHERE WO.[STATUS] = 'FINISHED'
