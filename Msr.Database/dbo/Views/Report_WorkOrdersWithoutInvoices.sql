	ROW_NUMBER() OVER(ORDER BY WO.LOCATIONNAME ASC) AS Id
	, WO.LOCATIONNAME AS LOCATION_NAME
	, WO.CUSTOMERNAME AS CUSTOMER_NAME
	, WO.REFERENCEPO AS CUST_PURCH_NUM
	, WO.WOITEM AS WORK_ORDER_ITEM
	, CASE WHEN (WO.PRODUCTNAME IS NULL) THEN N'' ELSE WO.PRODUCTNAME END + N'(' + CASE WHEN (WO.PROCOBJID IS NULL) THEN N'' ELSE WO.PROCOBJID END + N')' AS PRODUCT_NAME
	, FORMAT(WO.TOTALSALEPRICE, 'C') AS TOTAL_SALE_PRICE
	, FORMAT(WO.ACTUALSTOPDATE, 'MM/dd/yyyy') AS WORK_ORDER_COMPLETED_DATE
	--, WO.FILLITEMID
