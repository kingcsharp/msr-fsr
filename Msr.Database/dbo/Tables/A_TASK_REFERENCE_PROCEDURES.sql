CREATE TRIGGER A_TASK_REFERENCE_PROCEDURES_INSERT
ON dbo.A_TASK_REFERENCE_PROCEDURES
AFTER INSERT
AS
declare @taskID varchar(50)
SELECT @taskID = TASK_ID FROM INSERTED
UPDATE A_TASKS SET HAS_REF_PROC = 1 WHERE ID = @taskID

