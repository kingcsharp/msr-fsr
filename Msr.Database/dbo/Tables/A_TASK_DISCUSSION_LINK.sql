CREATE  TRIGGER A_TASK_DISCUSSION_LINK_INSERT
ON dbo.A_TASK_DISCUSSION_LINK
AFTER INSERT
AS
declare @taskID varchar(50),@discID varchar(50),@modby varchar(50)
SELECT @taskID = TASK_ID,@discID = DISCUSSION_ID,@modby = MODBY FROM INSERTED
exec A_SP_PROJECT_COPY_ONE_ITEMS_PROJ_OBJ_PURP_TAGS @discID,'A_DISCUSSIONS',@taskID,'A_TASKS',@modby
UPDATE A_TASKS SET HAS_DISCUSSION = 1 WHERE ID = @taskID


