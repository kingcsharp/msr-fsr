CREATE TABLE [dbo].[A_TASK_DISCUSSION_LINK] (
    [ID]            VARCHAR (50) NOT NULL,
    [TASK_ID]       VARCHAR (50) NULL,
    [DISCUSSION_ID] VARCHAR (50) NULL,
    [DRCM]          DATETIME     NULL,
    [MODBY]         VARCHAR (50) NULL,
    CONSTRAINT [PK_A_TASK_DISCUSSION_LINK] PRIMARY KEY CLUSTERED ([ID] ASC),
    CONSTRAINT [FK_A_TASK_DISCUSSION_LINK_A_DISCUSSIONS] FOREIGN KEY ([DISCUSSION_ID]) REFERENCES [dbo].[A_DISCUSSIONS] ([ID]) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT [FK_A_TASK_DISCUSSION_LINK_A_TASKS] FOREIGN KEY ([TASK_ID]) REFERENCES [dbo].[A_TASKS] ([ID]) ON DELETE CASCADE ON UPDATE CASCADE
);


GO
