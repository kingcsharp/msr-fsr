CREATE TABLE [dbo].[A_QUOTES_HISTORY] (
    [ID]              VARCHAR (50)    NOT NULL,
    [OBJECT_ID]       VARCHAR (50)    NULL,
    [DESCRIPTION]     NVARCHAR (1000) NULL,
    [PROGRESS]        VARCHAR (50)    NULL,
    [ORDER_ID]        VARCHAR (50)    NOT NULL,
    [DRCM]            DATETIME        NULL,
    [MODBY]           VARCHAR (50)    NULL,
    [CUSTOMER_PERSON] VARCHAR (50)    NULL,
    [CUSTOMER_CO]     VARCHAR (50)    NULL,
    [BUGETARY_ONLY]   SMALLINT        NULL,
    [EXPIRATION_DATE] DATETIME        NULL,
    [SUPPLIER_ID]     VARCHAR (50)    NULL,
    [CREATION_DATE]   DATETIME        NULL,
    [PERSON_SUPPLIER] VARCHAR (50)    NULL,
    CONSTRAINT [PK_A_QUOTES_HISTORY] PRIMARY KEY CLUSTERED ([ID] ASC),
    CONSTRAINT [FK_A_QUOTES_HISTORY_A_OBJECTS] FOREIGN KEY ([OBJECT_ID]) REFERENCES [dbo].[A_OBJECTS] ([ID]) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT [FK_A_QUOTES_HISTORY_A_ORDERS] FOREIGN KEY ([ORDER_ID]) REFERENCES [dbo].[A_ORDERS] ([ID])
);


GO
