CREATE  TRIGGER A_TASK_SURVEY_LINK_INSERT
ON dbo.A_TASK_SURVEY_LINK
AFTER INSERT
AS
declare @taskID varchar(50),@fromID varchar(50),@modby varchar(50)
SELECT @taskID = TASK_ID,@fromID = SURVEY_ID,@modby = MODBY FROM INSERTED
exec A_SP_PROJECT_COPY_ONE_ITEMS_PROJ_OBJ_PURP_TAGS @fromID,'A_SURVEYS',@taskID,'A_TASKS',@modby
UPDATE A_TASKS SET HAS_SURVEY = 1 WHERE ID = @taskID
