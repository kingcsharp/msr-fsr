CREATE TRIGGER [dbo].[A_ORDERS_HISTORY_UPDATE]
ON [dbo].[A_ORDERS_HISTORY]
AFTER UPDATE
AS

DECLARE @OBJ_ID AS NVARCHAR(50)
DECLARE @ID AS NVARCHAR(50)
DECLARE @NAME AS NVARCHAR(50)
DECLARE @MODBY AS NVARCHAR(50), @OLDCO AS VARCHAR(50), @NEWCO VARCHAR(50)

PRINT 'IN THE ORDERS HISTORY UPDATE TRIGGER'

SELECT	  @ID = ID
		, @OBJ_ID = [OBJECT_ID]
		, @NAME = [DESCRIPTION]
		, @MODBY = MODBY
		, @NEWCO = CUSTOMER_CO 
FROM INSERTED

PRINT ' THIS NAME IS ' + @NAME

DECLARE @MYOBJNAME AS NVARCHAR(100)

SELECT @MYOBJNAME = OBJ_DESC
FROM A_OBJECTS
WHERE ID = @OBJ_ID

IF @MYOBJNAME <> @NAME
BEGIN
	UPDATE A_OBJECTS SET
	OBJ_DESC = @NAME,
	MODBY = @MODBY,
	DRCM = GETDATE()
	WHERE ID = @OBJ_ID
END


