DECLARE @PRODUCT_ROOT_ID VARCHAR(50)
DECLARE @TOTAL_RELATED_REVISED_PRODUCTS INT

SET @NEW_ORDER_ID_BEING_INSERTED = @OBJ_ID

IF EXISTS (SELECT 'T' FROM A_OBJECTS WHERE ID = @NEW_ORDER_ID_BEING_INSERTED AND [STATUS] LIKE '%APPROVED%')
BEGIN

	SELECT @PRODUCT_ROOT_ID = [ROOT]
	FROM A_PRODUCTS_HISTORY PH
	INNER JOIN A_OBJECTS O ON O.ID = PH.OBJECT_ID
	INNER JOIN A_PRODUCTS_QUICK_PRICE QP ON QP.PROD_HIST_ID = PH.ID
	--INNER JOIN A_QUOTES_HISTORY QH ON QH.ID = QP.QUOTE_ID
	INNER JOIN A_ORDERS_HISTORY OH ON OH.OBJECT_ID = QP.ORDER_ID
	WHERE OH.OBJECT_ID = @NEW_ORDER_ID_BEING_INSERTED

	SELECT @TOTAL_RELATED_REVISED_PRODUCTS = COUNT(*)
	FROM A_OBJECTS O
	WHERE O.[ROOT] = @PRODUCT_ROOT_ID

	SELECT DISTINCT OH.OBJECT_ID AS ORDERID
	FROM A_PRODUCTS_HISTORY PH
	INNER JOIN A_OBJECTS O ON O.ID = PH.OBJECT_ID
	INNER JOIN A_PRODUCTS_QUICK_PRICE QP ON QP.PROD_HIST_ID = PH.ID
	INNER JOIN A_ORDERS_HISTORY OH ON OH.OBJECT_ID = QP.ORDER_ID
	WHERE O.[ROOT] = @PRODUCT_ROOT_ID
	ORDER BY OH.OBJECT_ID

	SELECT @NEW_ORDER_ID_BEING_INSERTED, @PRODUCT_ROOT_ID, @TOTAL_RELATED_REVISED_PRODUCTS

	IF @TOTAL_RELATED_REVISED_PRODUCTS >= 1
	BEGIN
		UPDATE A_ACCOUNT_PURCHASABLE_ORDERS_LINK SET
		ORDER_ID = @NEW_ORDER_ID_BEING_INSERTED
		WHERE ORDER_ID IN (
							SELECT DISTINCT OH.OBJECT_ID AS ORDERID
							FROM A_PRODUCTS_HISTORY PH
							INNER JOIN A_OBJECTS O ON O.ID = PH.OBJECT_ID
							INNER JOIN A_PRODUCTS_QUICK_PRICE QP ON QP.PROD_HIST_ID = PH.ID
							INNER JOIN A_ORDERS_HISTORY OH ON OH.OBJECT_ID = QP.ORDER_ID
							WHERE	O.[ROOT] = @PRODUCT_ROOT_ID
							AND		OH.OBJECT_ID <> @NEW_ORDER_ID_BEING_INSERTED
						  )
	END

END

