CREATE TABLE [dbo].[A_MONITOR_RESULTS] (
    [ID]                  VARCHAR (50)    NOT NULL,
    [MONITOR_TEMPLATE_ID] VARCHAR (50)    NULL,
    [NUM_VAL]             FLOAT (53)      NULL,
    [TEXT_VAL]            NVARCHAR (4000) NULL,
    [MULT_CHOICE_ANSWER]  VARCHAR (50)    NULL,
    [DRCM]                DATETIME        NULL,
    [MODBY]               VARCHAR (50)    NULL,
    [PRINT_RESULT]        NVARCHAR (200)  NULL,
    [COMMENT]             NVARCHAR (2000) NULL,
    CONSTRAINT [PK_A_MONITOR_RESULTS] PRIMARY KEY CLUSTERED ([ID] ASC)
);


GO





CREATE  TRIGGER A_MONITOR_RESULTS_INSERT_UPDATE
ON dbo.A_MONITOR_RESULTS
AFTER UPDATE, INSERT
AS
declare @ID varchar(50)
SELECT @ID = ID FROM INSERTED
declare @MONITOR_ID as nvarchar(50)
SELECT @MONITOR_ID = MONITOR_TEMPLATE_ID FROM A_MONITOR_RESULTS WHERE ID = @ID
exec A_SP_MONITOR_UPDATE_ALL_DATA @MONITOR_ID



