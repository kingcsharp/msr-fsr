CREATE TABLE [dbo].[A_THEORY_HISTORY] (
    [ID]             VARCHAR (50)    NOT NULL,
    [OBJECT_ID]      VARCHAR (50)    NULL,
    [NAME]           NVARCHAR (200)  NULL,
    [COMMENTS]       NVARCHAR (4000) NULL,
    [SECURITY_LEVEL] VARCHAR (50)    NOT NULL,
    [DRCM]           DATETIME        NULL,
    [MODBY]          VARCHAR (50)    NULL,
    [CREATING_DEPT]  VARCHAR (50)    NULL,
    CONSTRAINT [PK_A_THEORY_HISTORY] PRIMARY KEY CLUSTERED ([ID] ASC),
    CONSTRAINT [FK_A_THEORY_HISTORY_A_COMPANIES] FOREIGN KEY ([CREATING_DEPT]) REFERENCES [dbo].[A_COMPANIES] ([ID]),
    CONSTRAINT [FK_A_THEORY_HISTORY_A_OBJECTS] FOREIGN KEY ([OBJECT_ID]) REFERENCES [dbo].[A_OBJECTS] ([ID]) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT [FK_A_THEORY_HISTORY_A_SECURITY_LEVELS] FOREIGN KEY ([SECURITY_LEVEL]) REFERENCES [dbo].[A_SECURITY_LEVELS] ([ID]) ON DELETE CASCADE ON UPDATE CASCADE
);


GO
